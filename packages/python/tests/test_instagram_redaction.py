def _reader(*entries: tuple[str, str]) -> ZipArchiveReader:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, content in entries:
            zf.writestr(name, content)
    buf.seek(0)
    return ZipArchiveReader(buf, [name for name, _ in entries], Counter())


def _entry(label: str, value: str) -> dict:
    return {label: {"href": "", "value": value, "timestamp": 0}}


def _profile_json(username="jane.example", name="Jane Example",
                  label_username="Username", label_name="Name") -> str:
    data = {**_entry(label_username, username), **_entry(label_name, name)}
    return json.dumps({"profile_user": [{"title": "", "media_map_data": {}, "string_map_data": data}]})


def _signup_json(username: str) -> str:
    return json.dumps({"account_history_registration_info": [
        {"title": "", "media_map_data": {}, "string_map_data": _entry("Username", username)}]})


def _cells_page(**cells: str) -> str:
    rows = "".join(
        f'<tr><td colspan="2" class="_2pin _a6_q">{label}<div><div>{value}</div></div></td></tr>'
        for label, value in cells.items()
    )
    return f"<html><body><table>{rows}</table></body></html>"


def _start_page(username: str, dutch: bool = False) -> str:
    by, on = ("Gegenereerd door", "op") if dutch else ("Generated by", "on")
    return (f'<html><body><header><aside role="contentinfo" class="_aoaa">{by} {username} {on} '
            '<time datetime="2026-10-22T09:46Z">Oct 22, 2026</time></aside></header></body></html>')


