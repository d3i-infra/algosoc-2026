def _redacted(holder, **columns) -> pd.DataFrame:
    frame = pd.DataFrame(columns)
    instagram.redact_account_holder(
        [frame], holder, text_columns=None, link_columns=instagram.LINK_COLUMNS,
        skip_columns=instagram.DATE_COLUMNS,
        identifier_expression=instagram._identifier_expression, single_words_whole_cell=True,
    )
    return frame


def _posts_viewed(*authors: str) -> str:
    return json.dumps({"impressions_history_posts_seen": [
        {"string_map_data": {"Author": {"value": a}, "Time": {"timestamp": 1760000000}}} for a in authors]})


def _posts_viewed_page(*authors: str) -> str:
    sections = "".join(
        '<div class="_a6-g"><div><h2>Owner</h2><table>'
        f"<tr><td>Username</td><td>{a}</td></tr></table></div></div>"
        for a in authors
    )
    return f"<html><body><main>{sections}</main></body></html>"


class _Upload(io.BytesIO):
    """An upload with a file name, as the adapter in the browser has."""
    name = ""


def _tables(package_name: str, *entries: tuple[str, str], html: bool = False) -> tuple[dict, Counter]:
    # Validation needs three known names of the matching filetype; pad with names no extractor reads.
    pads = ["camera_information.html", "locations_of_interest.html"] if html else [
        "secret_conversations.json", "account_based_in.json"]
    wrapper = ""
    if entries and (match := re.match(r"instagram-[^/]+/", entries[0][0])):
        wrapper = match.group(0)
    buf = _Upload()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, content in entries:
            zf.writestr(name, content)
        for pad in pads:
            zf.writestr(wrapper + pad, "<html/>" if html else "[]")
    buf.seek(0)
    buf.name = package_name
    validation = validate.validate_zip(instagram.DDP_CATEGORIES, buf)
    assert validation.get_status_code_id() == 0
    result = instagram.extraction(buf, validation)
    return {t.id: t.data_frame for t in result.tables}, result.errors


class TestRedactionOfTextColumns:
    def test_handle_and_name_become_the_token_in_any_column(self):
        frame = _redacted(JANE, Author=["jane.example", "other.one"], Comment=["hi Jane Example", "hi Jane"], **{"Media owner": ["JANE.EXAMPLE", "other.one"]})
        assert list(frame["Author"]) == ["[user]", "other.one"]
        assert list(frame["Comment"]) == ["hi [user]", "hi Jane"]
        assert list(frame["Media owner"]) == ["[user]", "other.one"]

    def test_a_name_equal_to_the_handle_is_redacted_once_and_by_the_handle_rule(self):
        # The resolver drops such a name (Task 2), so the handle's dot-aware boundaries govern.
        same = instagram.AccountHolder((), "janeexample")
        frame = _redacted(same, Author=["janeexample", "by janeexample!", "janeexample.more"])
        assert list(frame["Author"]) == ["[user]", "by [user]!", "janeexample.more"]

    def test_another_persons_handle_containing_the_name_is_left(self):
        jane = instagram.AccountHolder(("Jane",), "jane.example")
        assert list(_redacted(jane, Author=["jane_x", "xjane", "jane"])["Author"]) == ["jane_x", "xjane", "[user]"]

    def test_a_one_word_display_name_is_redacted_only_as_a_whole_cell(self):
        donald = instagram.AccountHolder(("Donald",), "donald.example")
        frame = _redacted(donald, Author=["Donald", "Donald Trump", "donald.example"], Comment=["thanks Donald!", "by donald.example", "x"])
        assert list(frame["Author"]) == ["[user]", "Donald Trump", "[user]"]
        assert list(frame["Comment"]) == ["thanks Donald!", "by [user]", "x"]

    def test_a_two_word_display_name_is_redacted_wherever_it_stands_alone(self):
        assert list(_redacted(JANE, Comment=["Jane Example wrote", "Jane Example-Smith wrote"])["Comment"]) == ["[user] wrote", "Jane Example-Smith wrote"]

    def test_the_handle_inside_a_longer_handle_is_left(self):
        frame = _redacted(JANE, Author=["jane.example2", "jane.examples", "x.jane.example", "jane.example.more"])
        assert list(frame["Author"]) == ["jane.example2", "jane.examples", "x.jane.example", "jane.example.more"]
        frame = _redacted(JANE, Comment=["follow jane.example.", "@jane.example, hi"])
        assert list(frame["Comment"]) == ["follow [user].", "@[user], hi"]

    def test_an_address_becomes_its_own_token(self):
        assert list(_redacted(JANE, Comment=["mail jane.example@example.org"])["Comment"]) == ["mail [email]"]

    def test_a_numeric_handle_leaves_date_columns_whole(self):
        numeric = instagram.AccountHolder((), "1998")
        frame = _redacted(numeric, Author=["1998", "other.one"],
                          Date=["1998-10-22 09:46:00", "2026-10-22 19:98:00"], Timestamp=["1998-01-01 00:00:00", "x"])
        assert list(frame["Author"]) == ["[user]", "other.one"]
        assert list(frame["Date"]) == ["1998-10-22 09:46:00", "2026-10-22 19:98:00"]
        assert list(frame["Timestamp"]) == ["1998-01-01 00:00:00", "x"]

    def test_dates_and_missing_values_are_untouched(self):
        frame = _redacted(JANE, Date=["2026-10-22 09:46:00"], Comment=[None])
        assert list(frame["Date"]) == ["2026-10-22 09:46:00"] and frame["Comment"].isna().all()


class TestRedactionOfTheLinkColumn:
    def test_a_link_to_the_holder_is_masked_and_others_are_left(self):
        frame = _redacted(JANE, URL=["https://www.instagram.com/jane.example/p/abc/", "https://www.instagram.com/jane.example2/p/abc/", "https://www.instagram.com/p/abc/"])
        assert list(frame["URL"]) == ["https://www.instagram.com/[user]/p/abc/", "https://www.instagram.com/jane.example2/p/abc/", "https://www.instagram.com/p/abc/"]

    def test_a_link_to_a_longer_handle_that_starts_with_the_holders_is_left(self):
        assert list(_redacted(JANE, URL=["https://www.instagram.com/jane.example.more/"])["URL"]) == ["https://www.instagram.com/jane.example.more/"]

    def test_the_name_is_not_applied_to_links(self):
        assert list(_redacted(JANE, URL=["https://www.instagram.com/Jane Example/"])["URL"]) == ["https://www.instagram.com/Jane Example/"]


class TestExtractionRedacts:
    def test_a_json_export_is_redacted_from_its_profile_file(self):
        # A package name that resolves nothing, so only the profile file can supply the handle.
        tables, errors = _tables("my instagram data.zip", (PROFILE_JSON, _profile_json()), (POSTS_VIEWED_JSON, _posts_viewed("jane.example", "other.one")))
        assert sorted(tables["instagram_posts_viewed"]["Author"]) == ["[user]", "other.one"]

    def test_an_html_export_is_redacted_from_its_start_page(self):
        tables, _ = _tables("my instagram data.zip", (START_HTML, _start_page("jane.example")), (POSTS_VIEWED_HTML, _posts_viewed_page("jane.example", "other.one")), html=True)
        assert sorted(tables["instagram_posts_viewed"]["Author"]) == ["[user]", "other.one"]

    def test_a_renamed_zip_is_redacted_from_its_package_folder(self):
        tables, _ = _tables("my instagram data.zip", ("instagram-janeexample-2026-10-20-rgCknViv/" + POSTS_VIEWED_JSON, _posts_viewed("janeexample", "other.one")))
        assert sorted(tables["instagram_posts_viewed"]["Author"]) == ["[user]", "other.one"]

    def test_nothing_resolved_redacts_nothing_and_counts_no_error(self):
        tables, errors = _tables("my instagram data.zip", (POSTS_VIEWED_JSON, _posts_viewed("jane.example")))
        assert list(tables["instagram_posts_viewed"]["Author"]) == ["jane.example"]
        assert not errors  # if the other extractors count their missing files here, narrow to `set(errors) <= {<those keys>}` and name them in the handoff
