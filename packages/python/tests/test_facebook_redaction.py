class TestAccountHolderFromJson:
    def test_names_and_username_come_from_the_profile_file(self):
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json())))
        assert holder == facebook.AccountHolder(("Jane Example", "Jane Sample"), "jane.example")

    def test_an_account_without_a_username_gives_its_id(self):
        uri = f"https://www.facebook.com/profile.php?id={ACCOUNT_ID}"
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json(uri))))
        assert holder.identifier == ACCOUNT_ID

    def test_a_link_that_ends_in_a_number_gives_the_id(self):
        uri = f"https://www.facebook.com/{ACCOUNT_ID}"
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json(uri))))
        assert holder.identifier == ACCOUNT_ID

    def test_a_link_to_somewhere_else_gives_nothing(self):
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json("https://example.org/jane"))))
        assert holder.identifier is None

    def test_a_previous_name_written_as_a_record_or_as_text_is_taken(self):
        extra = {"previous_names": [{"name": "Jane Earlier", "timestamp": 1}, "Jane Before"]}
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json(**extra))))
        assert set(holder.names) == {"Jane Example", "Jane Sample", "Jane Earlier", "Jane Before"}

    def test_a_longer_name_stands_before_the_name_it_contains(self):
        extra = {"other_names": [{"name": "Jane Example-Sample", "type": "OTHER", "timestamp": 1}]}
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json(**extra))))
        assert holder.names == ("Jane Example-Sample", "Jane Example")

    def test_a_name_stored_as_escaped_bytes_is_decoded(self):
        profile = _profile_json().replace("Jane Example", "Jan\\u00c3\\u00a9 Example")
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, profile)))
        assert "Jané Example" in holder.names

    def test_a_profile_file_of_another_shape_resolves_nothing(self):
        assert facebook._resolve_account_holder(_reader((PROFILE_JSON, json.dumps(["unexpected"])))) == NOBODY

    def test_a_field_the_profile_file_lacks_is_asked_of_the_next_source(self):
        """The names from the profile file, the identifier from the package name."""
        reader = _reader((PROFILE_JSON, _profile_json(uri=None)))
        holder = facebook._resolve_account_holder(reader, "facebook-janeexample-2026-09-02-6zxl8WMW.zip")
        assert holder == facebook.AccountHolder(("Jane Example", "Jane Sample"), "janeexample")

    def test_a_host_that_only_ends_like_facebook_gives_nothing(self):
        uri = "https://notfacebook.com/jane.example"
        holder = facebook._resolve_account_holder(_reader((PROFILE_JSON, _profile_json(uri))))
        assert holder.identifier is None

