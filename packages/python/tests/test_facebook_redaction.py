def _redacted(holder: facebook.AccountHolder, **columns: list) -> pd.DataFrame:
    frame = pd.DataFrame(columns)
    facebook._redact_account_holder([frame], holder)
    return frame


JANE = facebook.AccountHolder(("Jane Example-Sample", "Jane Example", "Jane Sample"), "jane.example")


class TestRedactionOfTextColumns:
    def test_names_and_username_become_the_token(self):
        frame = _redacted(JANE, Title=["Jane Example liked a post", "jane sample's photo", "by janeexample"])
        assert list(frame["Title"]) == ["[user] liked a post", "[user]'s photo", "by [user]"]

    def test_a_name_is_matched_across_any_whitespace(self):
        frame = _redacted(JANE, Title=["Jane  Example wrote", "Jane Example wrote", "Jane\tExample"])
        assert list(frame["Title"]) == ["[user] wrote", "[user] wrote", "[user]"]

    def test_a_name_that_contains_another_is_redacted_whole(self):
        assert list(_redacted(JANE, Title=["Jane Example-Sample wrote"])["Title"]) == ["[user] wrote"]

    def test_another_person_whose_name_begins_with_it_is_left(self):
        frame = _redacted(JANE, Title=["Jane Example-Smith wrote", "Jane Examples", "John Example"])
        assert list(frame["Title"]) == ["Jane Example-Smith wrote", "Jane Examples", "John Example"]

    def test_an_address_becomes_its_own_token_also_when_it_holds_the_username(self):
        frame = _redacted(JANE, Comment=["write to jane.example@example.org or a@b.nl"])
        assert list(frame["Comment"]) == ["write to [email] or [email]"]

    def test_the_username_inside_a_longer_word_is_left(self):
        frame = _redacted(JANE, Comment=["jane.examples", "xjane.example", "janeexample2"])
        assert list(frame["Comment"]) == ["jane.examples", "xjane.example", "janeexample2"]

    def test_a_domain_named_after_the_account_holder_is_redacted(self):
        """Such a domain names them as surely as the username does."""
        frame = _redacted(JANE, Comment=["see www.janeexample.nl", "jane.example.com/about"])
        assert list(frame["Comment"]) == ["see www.[user].nl", "[user].com/about"]

    def test_a_username_known_with_its_dots_does_not_match_other_dots(self):
        assert list(_redacted(JANE, Comment=["j.ane.example"])["Comment"]) == ["j.ane.example"]

    def test_a_username_known_without_dots_matches_the_dotted_spelling(self):
        holder = facebook.AccountHolder((), "janeexample")
        assert list(_redacted(holder, Comment=["facebook.com/jane.example"])["Comment"]) == ["facebook.com/[user]"]

    def test_the_search_terms_are_a_text_column(self):
        frame = _redacted(JANE, **{"Search term": ["Jane Example", "bicycles"]})
        assert list(frame["Search term"]) == ["[user]", "bicycles"]

    def test_missing_cells_stay_missing(self):
        frame = _redacted(JANE, Title=["Jane Example", None])
        assert frame["Title"][0] == "[user]" and pd.isna(frame["Title"][1])

    def test_nobody_resolved_still_redacts_addresses(self):
        frame = _redacted(NOBODY, Title=["Jane Example wrote to a@b.nl"])
        assert list(frame["Title"]) == ["Jane Example wrote to [email]"]

    def test_a_name_with_characters_special_to_a_pattern_is_taken_literally(self):
        holder = facebook.AccountHolder(("J. (Jane) Example",), None)
        assert list(_redacted(holder, Title=["J. (Jane) Example wrote", "Jx (Jane) Example"])["Title"]) == [
            "[user] wrote", "Jx (Jane) Example",
        ]


class TestRedactionOfLinkColumns:
    def test_the_username_is_redacted_and_the_rest_of_the_link_kept(self):
        frame = _redacted(JANE, URL=["https://www.facebook.com/jane.example/posts/123", "https://example.org/jane"])
