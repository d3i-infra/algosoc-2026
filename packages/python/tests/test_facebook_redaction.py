class TestNameFromTheReactionsFile:
    def test_every_reaction_by_the_same_actor_gives_the_name(self):
        reader = _reader((REACTIONS, _reactions("Jane Example", "Jane Example", "Jane Example")))
        assert facebook._resolve_account_holder(reader).names == ("Jane Example",)

    def test_two_actors_give_nothing(self):
        """The file holds the participant's own reactions. If it names more than one
        actor it is not the file this rule understands, and the more frequent of the
        two could be another person."""
        reader = _reader((REACTIONS, _reactions("Jane Example", "Jane Example", "John Example")))
        assert facebook._resolve_account_holder(reader).names == ()

    def test_the_profile_file_is_preferred_and_the_reactions_file_not_opened(self, monkeypatch):
        reader = _reader((PROFILE_JSON, _profile_json()), (REACTIONS, _reactions("Someone Else")))
        opened = []
        json_all = ZipArchiveReader.json_all
        monkeypatch.setattr(
            ZipArchiveReader, "json_all", lambda self, pattern: opened.append(pattern) or json_all(self, pattern)
        )
        assert "Someone Else" not in facebook._resolve_account_holder(reader).names
        assert opened == []

    def test_no_reactions_give_nothing(self):
        assert facebook._resolve_account_holder(_reader((REACTIONS, "[]"))).names == ()


