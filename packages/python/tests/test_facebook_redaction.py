def _reader(*entries: tuple[str, str]) -> ZipArchiveReader:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, content in entries:
            zf.writestr(name, content)
    buf.seek(0)
    return ZipArchiveReader(buf, [name for name, _ in entries], Counter())


def _profile_json(uri: str | None = "https://www.facebook.com/jane.example", **extra) -> str:
    profile = {
        "name": {"full_name": "Jane Example", "first_name": "Jane", "middle_name": "", "last_name": "Example"},
        "other_names": [{"name": "Jane Sample", "type": "MAIDEN", "timestamp": 1500000000}],
        "previous_names": [],
    }
    if uri is not None:
        profile["profile_uri"] = uri
    profile.update(extra)
    return json.dumps({"profile_v2": profile})


def _page(body: str = "", name: str = "Jane Example") -> str:
    return (
        '<html><head><meta charset="utf-8"></head><body><header>'
        f'<aside role="contentinfo" class="_aoaa">Generated by {name} on '
        '<time datetime="2026-09-02T13:11Z">Sep 02, 2026</time></aside></header>'
        f"<main>{body}</main></body></html>"
    )


def _profile_page(link: str = "https://www.facebook.com/jane.example", name: str = "Jane Example") -> str:
    return _page(
        "<table>"
        f"<tr><th>Name</th><td>{name}<br /></td></tr>"
        f'<tr><th>Profile</th><td><a href="{link}">{link}</a></td></tr>'
        "<tr><th>Other names</th><td><ul><li>Jane Sample</li></ul></td></tr>"
        "</table>",
        name=name,
    )


def _reactions(*actors: str) -> str:
    return json.dumps([
        {"timestamp": 1750000000 + n, "title": f"{actor} liked a post.",
         "data": [{"reaction": {"reaction": "LIKE", "actor": actor}}]}
        for n, actor in enumerate(actors)
    ])


